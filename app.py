        if jogado:
            st.success(f"✅ ENCERRADO [Resultado na Planilha: {res}]")
        else:
            if match_id not in st.session_state.simulacoes:
                st.session_state.simulacoes[match_id] = {"home": 40, "draw": 20, "away": 40}

            current = st.session_state.simulacoes[match_id]

            # Opção de travar (Lock) / Fixar resultado absoluto
            lock_opcao = st.selectbox(
                f"Fixar resultado para {row['home']} x {row['away']}?",
                ["Livre (Probabilidades)", f"Vitória {row['home']} (100%)", "Empate Total (100%)", f"Vitória {row['away']} (100%)"],
                key=f"lock_{match_id}"
            )

            if lock_opcao != "Livre (Probabilidades)":
                if "Mandante" in lock_opcao:
                    st.session_state.simulacoes[match_id] = {"home": 100, "draw": 0, "away": 0}
                elif "Empate" in lock_opcao:
                    st.session_state.simulacoes[match_id] = {"home": 0, "draw": 100, "away": 0}
                else:
                    st.session_state.simulacoes[match_id] = {"home": 0, "draw": 0, "away": 100}
                st.info("Simulation lock ativado para este jogo.")
            else:
                # Sliders incrementais garantindo a soma de 100%
                h_pct = st.slider(f"Vitória {row['home']} (%)", 0, 100, current["home"], 10, key=f"h_{match_id}")

                max_d = 100 - h_pct
                d_pct = st.slider("Empate (%)", 0, max_d, min(current["draw"], max_d), 10, key=f"d_{match_id}")

                a_pct = 100 - h_pct - d_pct
                st.markdown(f"📌 **Distribuição:** {h_pct}% Mandante | {d_pct}% Empate | **{a_pct}% Visitante** (Soma: 100%)")

                st.session_state.simulacoes[match_id] = {"home": h_pct, "draw": d_pct, "away": a_pct}