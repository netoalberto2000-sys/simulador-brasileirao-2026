    rodada_escolhida = st.selectbox("Selecione a Rodada:", [35, 36, 37, 38])

    jogos_rodada = df_jogos[df_jogos["rodada"] == rodada_escolhida]

    for _, row in jogos_rodada.iterrows():
        match_id = int(row["id"])
        res = str(row["resultado"]).strip().upper()
        jogado = res in ["H", "D", "A"]

        st.markdown("---")
