# Leitura da planilha de jogos
try:
    df_jogos = pd.read_csv("jogos_brasileirao_2026.csv").fillna("")
except FileNotFoundError:
    st.error("⚠️ O arquivo 'jogos_brasileirao_2026.csv' não foi encontrado! Certifique-se de enviá-lo junto com o app.py.")
    st.stop()

if "simulacoes" not in st.session_state:
    st.session_state.simulacoes = {}

def calcular_classificacao():
    tabela_final = {time: {"pontos": dados["pontos"], "jogos": dados["jogos"]} for time, dados in tabela_base.items()}

    for _, row in df_jogos.iterrows():
        match_id = int(row["id"])
        res = str(row["resultado"]).strip().upper()
        jogado = res in ["H", "D", "A"]

        if jogado:
            pts_h = 3 if res == "H" else (1 if res == "D" else 0)
            pts_a = 0 if res == "H" else (1 if res == "D" else 3)

            tabela_final[row["home"]]["pontos"] += pts_h
            tabela_final[row["home"]]["jogos"] += 1
            tabela_final[row["away"]]["pontos"] += pts_a
            tabela_final[row["away"]]["jogos"] += 1

        elif match_id in st.session_state.simulacoes:
            sim = st.session_state.simulacoes[match_id]
            p_h, p_d, p_a = sim["home"]/100.0, sim["draw"]/100.0, sim["away"]/100.0

            tabela_final[row["home"]]["pontos"] += (3 * p_h) + (1 * p_d)
            tabela_final[row["home"]]["jogos"] += 1
            tabela_final[row["away"]]["pontos"] += (3 * p_a) + (1 * p_d)
            tabela_final[row["away"]]["jogos"] += 1

    return sorted(tabela_final.items(), key=lambda x: x[1]["pontos"], reverse=True)

